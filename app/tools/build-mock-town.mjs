// Writes app/public/mock-town.js (the in-browser mock's copy of the SAMPLE town) from data/town.json, which the lead owns.
// The Worker never serves data/, so the mock needs its own copy. Run after `npm run town`: node app/tools/build-mock-town.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const town = JSON.parse(readFileSync(path.join(HERE, '..', '..', 'data', 'town.json'), 'utf8'))
const out = {
  name: town.name,
  center: town.center,
  zoom: town.zoom,
  boundary: town.boundary,
  wards: town.wards,
  streets: town.streets.map((s) => ({ name: s.name, point: s.point, lines: s.lines })),
  // SAMPLE settings, as in the Worker's 0002_sample migration (709-555-01xx is the range reserved for fiction).
  emergency_phone: '709-555-0142',
  office_phone: '709-555-0100',
  office_hours: 'Monday to Friday, 9 AM to 4:30 PM',
}
const file = path.join(HERE, '..', 'public', 'mock-town.js')
writeFileSync(file, `// Generated by app/tools/build-mock-town.mjs from data/town.json. Do not edit. Development mock only (?mock=1).\nexport const TOWN = ${JSON.stringify(out)}\n`)
console.log(`wrote ${path.relative(process.cwd(), file)}: ${out.streets.length} streets`)
