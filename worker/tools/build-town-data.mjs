// Reads ../data/town.json and ../data/test-points.json (lead-owned) and writes src/town-data.js (the Worker's copy) and
// tests/test-points.js (the tests' copy). Both outputs are committed: the Worker and its negative-control copies never read
// outside worker/. Run: npm run town

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const data = join(root, '..', 'data')
const town = JSON.parse(readFileSync(join(data, 'town.json'), 'utf8'))
const points = JSON.parse(readFileSync(join(data, 'test-points.json'), 'utf8'))

const byName = (a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0)
const out = {
  name: town.name,
  center: town.center,
  zoom: town.zoom,
  boundary: town.boundary,
  wards: town.wards.map(w => ({ id: w.id, name: w.name, polygon: w.polygon })),
  streets: [...town.streets].sort(byName).map(s => ({ name: s.name, point: s.point, lines: s.lines }))
}

const header = '// GENERATED by tools/build-town-data.mjs from data/town.json. Do not edit; run `npm run town`.\n'
writeFileSync(join(root, 'src', 'town-data.js'), `${header}export const TOWN = ${JSON.stringify(out)}\n`)
writeFileSync(join(root, 'tests', 'test-points.js'),
  `// GENERATED by tools/build-town-data.mjs from data/test-points.json. Do not edit; run \`npm run town\`.\nexport const POINTS = ${JSON.stringify(points, null, 2)}\n`)
console.log(`town-data.js: ${out.streets.length} streets, ${out.wards.length} wards; test-points.js written`)
